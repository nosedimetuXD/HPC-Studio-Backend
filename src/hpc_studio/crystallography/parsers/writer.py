"""Structure writers for CIF, XYZ, and Quantum ESPRESSO formats."""

from __future__ import annotations

from pathlib import Path
from typing import Optional, Union

from hpc_studio.crystallography.models import CrystalStructure
from hpc_studio.crystallography.parsers.xyz import write_xyz


def write_cif(
    structure: CrystalStructure,
    filepath_or_buffer: Optional[Union[str, Path]] = None,
) -> str:
    """Export CrystalStructure to standard CIF format string."""
    name = structure.name if structure.name else structure.formula() or "crystal"
    clean_name = "".join(c if c.isalnum() or c == "_" else "_" for c in name)

    lines = [
        f"data_{clean_name}",
        "# Generated by HPC Studio Linux",
        "_audit_creation_method 'HPC Studio Crystallography Core'",
        "",
    ]

    lat = structure.lattice
    if lat is not None:
        lines.extend([
            f"_cell_length_a                   {lat.a:.6f}",
            f"_cell_length_b                   {lat.b:.6f}",
            f"_cell_length_c                   {lat.c:.6f}",
            f"_cell_angle_alpha                {lat.alpha:.4f}",
            f"_cell_angle_beta                 {lat.beta:.4f}",
            f"_cell_angle_gamma                {lat.gamma:.4f}",
            f"_cell_volume                     {lat.volume:.4f}",
            "_symmetry_space_group_name_H-M   'P 1'",
            "_symmetry_Int_Tables_number      1",
            "",
        ])

    # Atom loop
    lines.extend([
        "loop_",
        "_atom_site_label",
        "_atom_site_type_symbol",
        "_atom_site_fract_x",
        "_atom_site_fract_y",
        "_atom_site_fract_z",
    ])

    for i, atom in enumerate(structure.atoms):
        lbl = f"{atom.symbol}{i+1}"
        sym = atom.symbol
        if atom.fractional_position is not None:
            fx, fy, fz = atom.fractional_position
        elif lat is not None:
            fx, fy, fz = lat.cartesian_to_fractional(atom.position)
        else:
            fx, fy, fz = atom.position

        lines.append(f"{lbl:<8} {sym:<4} {fx:12.6f} {fy:12.6f} {fz:12.6f}")

    lines.append("")
    content = "\n".join(lines)

    if filepath_or_buffer is not None:
        if isinstance(filepath_or_buffer, (str, Path)):
            Path(filepath_or_buffer).write_text(content, encoding="utf-8")
        else:
            filepath_or_buffer.write(content)

    return content


def write_qe_blocks(
    structure: CrystalStructure,
    pseudopotentials: Optional[dict[str, str]] = None,
) -> str:
    """Generate Quantum ESPRESSO input cards (CELL_PARAMETERS, ATOMIC_SPECIES, ATOMIC_POSITIONS)."""
    lines = []
    lat = structure.lattice

    if lat is not None:
        lines.append("CELL_PARAMETERS (angstrom)")
        for vec in lat.matrix:
            lines.append(f"  {vec[0]:15.9f}  {vec[1]:15.9f}  {vec[2]:15.9f}")
        lines.append("")

    # Unique species
    species = sorted(list({atom.symbol for atom in structure.atoms}))
    lines.append("ATOMIC_SPECIES")
    for s in species:
        pseudo = (
            pseudopotentials.get(s, f"{s}.pbe-n-kjpaw_psl.1.0.0.UPF")
            if pseudopotentials
            else f"{s}.UPF"
        )
        mass = structure.atoms[0].element_data.atomic_mass
        # find matching mass for species
        for at in structure.atoms:
            if at.symbol == s:
                mass = at.element_data.atomic_mass
                break
        lines.append(f"  {s:<3}  {mass:8.4f}  {pseudo}")
    lines.append("")

    # Atomic positions
    if lat is not None:
        lines.append("ATOMIC_POSITIONS (crystal)")
        for atom in structure.atoms:
            fx, fy, fz = (
                atom.fractional_position
                if atom.fractional_position is not None
                else lat.cartesian_to_fractional(atom.position)
            )
            lines.append(f"  {atom.symbol:<3}  {fx:14.9f}  {fy:14.9f}  {fz:14.9f}")
    else:
        lines.append("ATOMIC_POSITIONS (angstrom)")
        for atom in structure.atoms:
            x, y, z = atom.position
            lines.append(f"  {atom.symbol:<3}  {x:14.9f}  {y:14.9f}  {z:14.9f}")
    lines.append("")

    return "\n".join(lines)


__all__ = ["write_cif", "write_xyz", "write_qe_blocks"]
