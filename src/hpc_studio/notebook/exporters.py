"""Notebook exporter utilities for HPC Studio.

Converts Jupyter NotebookDocument instances into clean Python scripts,
production-ready SLURM submission scripts, and Quantum ESPRESSO pw.x input decks.
"""

from __future__ import annotations

import re
from typing import Optional, Union, Any

from .models import CellType, NotebookDocument


class NotebookExporter:
    """Provides methods to export a NotebookDocument to various HPC target formats."""

    @classmethod
    def export_to_python(cls, doc: NotebookDocument) -> str:
        """Cleanly extract code cells and convert Markdown cells into formatted block comments.

        Preserves structure with `# %% [markdown]` and `# %%` cell delimiters,
        and comments out or handles IPython/Jupyter magic commands safely.

        Args:
            doc: NotebookDocument instance to export.

        Returns:
            Clean, valid Python script string.
        """
        sections: list[str] = [
            "#!/usr/bin/env python3",
            "# -*- coding: utf-8 -*-",
            '"""Exported from HPC Studio Notebook."""',
            "",
        ]

        for idx, cell in enumerate(doc.cells):
            source = (cell.source or "").strip()
            if not source:
                continue

            if cell.cell_type == CellType.MARKDOWN:
                sections.append("# %% [markdown]")
                # Format each line as a commented block
                commented_lines = [f"# {line}" if line else "#" for line in source.splitlines()]
                sections.append("\n".join(commented_lines))
                sections.append("")

            elif cell.cell_type == CellType.CODE:
                sections.append(f"# %% [code] Cell {idx + 1}")
                processed_lines: list[str] = []
                for line in source.splitlines():
                    stripped = line.strip()
                    # Comment out magic commands (% or %%) and shell escapes (! or ?)
                    if stripped.startswith(("%", "!", "?")):
                        processed_lines.append(f"# [magic/shell] {line}")
                    else:
                        processed_lines.append(line)
                sections.append("\n".join(processed_lines))
                sections.append("")

            elif cell.cell_type == CellType.RAW:
                sections.append("# %% [raw]")
                commented_lines = [f"# {line}" if line else "#" for line in source.splitlines()]
                sections.append("\n".join(commented_lines))
                sections.append("")

        return "\n".join(sections).rstrip() + "\n"

    @classmethod
    def export_to_slurm(
        cls,
        doc: NotebookDocument,
        job_name: str = "hpc_notebook_job",
        nodes: int = 1,
        ntasks: int = 4,
        time: str = "02:00:00",
        partition: str = "standard",
        mem: str = "8G",
    ) -> str:
        """Generate a production-ready SLURM (.sbatch) script from the notebook.

        Includes `#SBATCH` directives, environment module loading commands,
        and embedded execution of the converted Python code.

        Args:
            doc: NotebookDocument instance to export.
            job_name: SLURM job name.
            nodes: Number of compute nodes requested.
            ntasks: Total number of tasks / cores requested.
            time: Wall clock time limit (e.g. "02:00:00").
            partition: SLURM partition / queue name.
            mem: Memory per node requirement (e.g. "8G").

        Returns:
            Complete .sbatch script string.
        """
        # Sanitize parameters against newline injection and malicious characters
        safe_param_pattern = re.compile(r"^[a-zA-Z0-9_\-\.:]+$")

        def _clean_param(val: str, default: str) -> str:
            val_str = str(val).strip()
            if not safe_param_pattern.match(val_str):
                # Replace invalid chars with underscores to prevent directive/newline injection
                sanitized = re.sub(r"[^a-zA-Z0-9_\-\.:]", "_", val_str)
                return sanitized or default
            return val_str

        job_name = _clean_param(job_name, "hpc_notebook_job")
        partition = _clean_param(partition, "standard")
        time = _clean_param(time, "02:00:00")
        mem = _clean_param(mem, "8G")
        try:
            nodes = max(1, int(nodes))
        except (ValueError, TypeError):
            nodes = 1
        try:
            ntasks = max(1, int(ntasks))
        except (ValueError, TypeError):
            ntasks = 4

        python_code = cls.export_to_python(doc)

        header = f"""#!/bin/bash
# ==============================================================================
# SLURM Batch Job Script generated by HPC Studio Linux
# Job: {job_name}
# ==============================================================================
#SBATCH --job-name={job_name}
#SBATCH --output=%x_%j.out
#SBATCH --error=%x_%j.err
#SBATCH --nodes={nodes}
#SBATCH --ntasks={ntasks}
#SBATCH --time={time}
#SBATCH --partition={partition}
#SBATCH --mem={mem}

# --- HPC Environment Setup ---
# Purge and load required environment modules (adapt as needed for cluster)
if command -v module &> /dev/null; then
    module purge
    module load python/3.10 2>/dev/null || module load python3 2>/dev/null || true
fi

echo "Job started on $(hostname) at $(date)"
echo "Running in directory: $(pwd)"
echo "Allocated cores: $SLURM_NTASKS"

# --- Embedded Notebook Execution ---
python3 - << 'EOF'
{python_code}
EOF

EXIT_CODE=$?
echo "Job finished at $(date) with exit code $EXIT_CODE"
exit $EXIT_CODE
"""
        return header

    @classmethod
    def export_to_qe_input(cls, doc: NotebookDocument) -> Optional[str]:
        """Scan notebook cells and metadata for Quantum ESPRESSO parameters and structures.

        Attempts to extract either:
        1. Explicit QE pw.x input blocks in raw/code/markdown cells (&CONTROL ... ATOMIC_POSITIONS).
        2. Crystallographic structure objects or metadata stored in cell/notebook metadata.
        3. Python variables defining QE input strings or structures.

        Returns:
            Standard pw.x input formatted string if found, or None if no QE data detected.
        """
        # 1. First check notebook metadata for explicit qe_input or crystal_structure
        nb_meta = doc.metadata or {}
        if "qe_input" in nb_meta:
            qe_val = nb_meta["qe_input"]
            if isinstance(qe_val, str) and "&CONTROL" in qe_val.upper():
                return qe_val.strip() + "\n"

        # 2. Check each cell's metadata and cell content
        # Patterns matching a Quantum ESPRESSO input deck
        qe_deck_pattern = re.compile(r"(&CONTROL[\s\S]*?(?:ATOMIC_POSITIONS|K_POINTS)[\s\S]*?)(?:$|(?=```))", re.IGNORECASE)

        for cell in doc.cells:
            # Check cell metadata
            c_meta = cell.metadata or {}
            if "qe_input" in c_meta and isinstance(c_meta["qe_input"], str):
                val = c_meta["qe_input"].strip()
                if "&CONTROL" in val.upper():
                    return val + "\n"

            # Check if cell has crystal_structure in metadata
            if "crystal_structure" in c_meta:
                try:
                    from hpc_studio.crystallography.models import CrystalStructure
                    from hpc_studio.crystallography.qe_models import QEInput as CrysQEInput
                    struct_data = c_meta["crystal_structure"]
                    if isinstance(struct_data, CrystalStructure):
                        qe_obj = CrysQEInput.from_crystal_structure(struct_data)
                        return qe_obj.to_string()
                    elif isinstance(struct_data, dict):
                        # Reconstruct if dict representation
                        lat_data = struct_data.get("lattice")
                        atoms_data = struct_data.get("atoms", [])
                        from hpc_studio.crystallography.models import Atom, Lattice
                        lat = Lattice(lat_data) if lat_data is not None else None
                        atoms = [
                            Atom(
                                index=a.get("index", idx),
                                symbol=a.get("symbol", "X"),
                                position=tuple(a.get("position", (0.0, 0.0, 0.0))),
                                fractional_position=tuple(a["fractional_position"]) if a.get("fractional_position") else None,
                            )
                            for idx, a in enumerate(atoms_data)
                        ]
                        struct = CrystalStructure(lattice=lat, atoms=atoms)
                        qe_obj = CrysQEInput.from_crystal_structure(struct)
                        return qe_obj.to_string()
                except Exception:
                    pass

            source = cell.source or ""

            # Check for inline raw QE input deck in source (Markdown triple backticks or Raw cell)
            deck_match = qe_deck_pattern.search(source)
            if deck_match:
                candidate = deck_match.group(1).strip()
                # Verify that parse_qe_input or QEInput can recognize it
                try:
                    from hpc_studio.qe import parse_qe_input
                    parsed = parse_qe_input(candidate)
                    return parsed.to_string()
                except Exception:
                    try:
                        from hpc_studio.crystallography.qe_models import QEInput as CrysQEInput
                        parsed2 = CrysQEInput.from_string(candidate)
                        return parsed2.to_string()
                    except Exception:
                        # Fallback to candidate text directly if valid blocks
                        if "&CONTROL" in candidate.upper() and ("&SYSTEM" in candidate.upper() or "ATOMIC_POSITIONS" in candidate.upper()):
                            return candidate + "\n"

            # Check for Python variable assignments with multi-line QE input or QEInput constructor
            # e.g., qe_str = """&CONTROL ... """
            if "&CONTROL" in source.upper():
                # Extract text between triple quotes if present
                triple_quote_match = re.search(r'("""|\'\'\')([\s\S]*?&CONTROL[\s\S]*?)\1', source, re.IGNORECASE)
                if triple_quote_match:
                    raw_block = triple_quote_match.group(2).strip()
                    try:
                        from hpc_studio.qe import parse_qe_input
                        parsed = parse_qe_input(raw_block)
                        return parsed.to_string()
                    except Exception:
                        return raw_block + "\n"

        # 3. Check if any code cell creates a CrystalStructure or QEInput and reconstruct
        # If nothing was found, return None
        return None

    @classmethod
    def export_to_quantum_espresso(cls, doc: NotebookDocument) -> str:
        """Export notebook to Quantum ESPRESSO input file (.in).
        
        Extracts QE input if present in cells or metadata, or provides a default template.
        """
        qe_content = cls.export_to_qe_input(doc)
        if qe_content:
            return qe_content

        return """! Quantum ESPRESSO Input File
! Exportado desde HPC Studio Notebook

&CONTROL
  calculation = 'scf',
  restart_mode = 'from_scratch',
  prefix = 'hpc_calc',
  outdir = './tmp/',
  pseudo_dir = './pseudo/',
/
&SYSTEM
  ibrav = 2,
  celldm(1) = 10.26,
  nat = 2,
  ntyp = 1,
  ecutwfc = 30.0,
/
&ELECTRONS
  conv_thr = 1.0d-8,
  mixing_beta = 0.7,
/
ATOMIC_SPECIES
  Si  28.086  Si.pbe-n-kjpaw_psl.1.0.0.UPF

ATOMIC_POSITIONS (alat)
  Si  0.000000000  0.000000000  0.000000000
  Si  0.250000000  0.250000000  0.250000000

K_POINTS (automatic)
  4 4 4  1 1 1
"""


